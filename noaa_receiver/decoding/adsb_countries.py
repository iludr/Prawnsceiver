import bisect

_STARTS = [r[0] for r in ICAO_COUNTRY_RANGES]


def icao_country(icao_hex):
    """'4840D6' -> ('Germany', 'de') or (None, None)."""
    try:
        v = int(icao_hex, 16)
    except (ValueError, TypeError):
        return None, None
    i = bisect.bisect_right(_STARTS, v) - 1
    if i >= 0:
        s, e, c, cc = ICAO_COUNTRY_RANGES[i]
        if s <= v <= e:
            return c, cc
    return None, None
